static int font_index(char c) {
    if (c >= 'A' && c <= 'Z') return c - 'A' + 1;
    if (c >= 'a' && c <= 'z') return c - 'a' + 1;
    if (c >= '0' && c <= '9') return c - '0' + 27;
    return 0;
}

// 0x80 selects a command; framebuffer transfers use 0x40.
static void send_cmd(uint8_t cmd) {
    uint8_t b[2] = { 0x80, cmd };
    i2c_write_blocking(s_i2c, s_addr, b, 2, false);
}

void ssd1306_init(i2c_inst_t *i2c, uint8_t addr) {
    s_i2c  = i2c;
    s_addr = addr;

    static const uint8_t cmds[] = {
        CMD_SET_DISP,
        CMD_SET_MEM_MODE, 0x00,
        CMD_SET_START_LINE,
        CMD_SET_SEG_REMAP | 0x01,
        CMD_SET_MUX_RATIO, SSD1306_HEIGHT - 1,
        CMD_SET_COM_OUT_DIR | 0x08,
        CMD_SET_DISP_OFFSET, 0x00,
        CMD_SET_COM_PIN_CFG, 0x12,
        CMD_SET_DISP_CLK_DIV, 0x80,
        CMD_SET_PRECHARGE, 0xF1,
        CMD_SET_VCOM_DESEL, 0x30,
        CMD_SET_CONTRAST, 0xFF,
        CMD_SET_ENTIRE_ON,
        CMD_SET_NORM_DISP,
        CMD_SET_CHARGE_PUMP, 0x14,
        CMD_SET_DISP | 0x01,
    };
    for (uint i = 0; i < sizeof(cmds); i++) send_cmd(cmds[i]);

    ssd1306_clear();
    ssd1306_show();
}

void ssd1306_clear(void) {
    memset(s_buf, 0, BUF_LEN);
}

void ssd1306_show(void) {

    send_cmd(CMD_SET_COL_ADDR);  send_cmd(0); send_cmd(SSD1306_WIDTH - 1);
    send_cmd(CMD_SET_PAGE_ADDR); send_cmd(0); send_cmd(SSD1306_ROWS - 1);

    uint8_t out[BUF_LEN + 1];
    out[0] = 0x40;
    memcpy(out + 1, s_buf, BUF_LEN);
    i2c_write_blocking(s_i2c, s_addr, out, BUF_LEN + 1, false);
}

void ssd1306_text(uint col, uint row, const char *s) {
    if (row >= SSD1306_ROWS) return;

    for (; *s && col < SSD1306_COLS; s++, col++) {
        const uint8_t *g = &FONT[font_index(*s) * 8];
        uint8_t *dst = &s_buf[row * SSD1306_WIDTH + col * 8];
        for (int i = 0; i < 8; i++) dst[i] = g[i];
    }
}

void ssd1306_pixel(uint x, uint y, bool on) {
    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) return;

    uint idx  = (y / 8) * SSD1306_WIDTH + x;
    uint8_t m = 1u << (y % 8);

    if (on) s_buf[idx] |=  m;
    else    s_buf[idx] &= ~m;
}

void ssd1306_display_on(bool on) {
    send_cmd(on ? (CMD_SET_DISP | 0x01) : CMD_SET_DISP);
}
